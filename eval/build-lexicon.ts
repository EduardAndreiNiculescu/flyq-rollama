/**
 * Builds src/data/common-words.json: ordinary words that the spell-corrector must NEVER change.
 * Sources: the system prompt, the knowledge base and the v2 TRAINING/VALIDATION text. The hand-written
 * evaluation questions are deliberately NOT used, so false-correction rates measured on them stay honest.
 *   npx tsx eval/build-lexicon.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { KNOWLEDGE_BASE } from '../src/core/knowledge';
import { SYSTEM_PROMPT } from '../src/core/prompt';

const plain = (s: string) => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
const words = new Set<string>();
const take = (text: string) => plain(text).split(/[^a-z]+/).filter((w) => w.length >= 4).forEach((w) => words.add(w));

take(SYSTEM_PROMPT);
for (const e of KNOWLEDGE_BASE) take(`${e.title} ${e.body} ${e.keywords.join(' ')}`);
for (const f of ['train', 'val']) {
  const p = fileURLToPath(new URL(`../finetune/data/v2/${f}.jsonl`, import.meta.url));
  for (const line of readFileSync(p, 'utf8').split('\n').filter(Boolean)) {
    const row = JSON.parse(line) as { messages: { role: string; content: string }[] };
    // Skip the long system message (it repeats the prompt + facts); user and assistant turns are natural text.
    for (const m of row.messages) if (m.role !== 'system') take(m.content);
  }
}
const out = [...words].sort();
writeFileSync(fileURLToPath(new URL('../src/data/common-words.json', import.meta.url)), JSON.stringify({ _note: 'generated by eval/build-lexicon.ts; do not edit', words: out }));
console.log(`common words: ${out.length}`);
